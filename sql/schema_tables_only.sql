-- =====================================================================
-- Schéma e-commerce : CRÉATION DES TABLES UNIQUEMENT
-- (clés primaires/étrangères, contraintes, index)
-- PostgreSQL 15+ (Supabase ou local). Sans RLS, policies, droits ni triggers.
--
-- Aucun nom de table ni de colonne du schéma d'origine n'est renommé.
-- Colonnes ajoutées : categorie.category_parent_id, commandes.commande_adress_id,
-- product_pivot.pivot_created_at.
-- Rappel : sans trigger, variantes.variante_price, product.product_categorie et
-- category_pivot ne se mettent pas à jour automatiquement (le seeder s'en charge).
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. UTILISATEURS & ADRESSES
-- ---------------------------------------------------------------------
create table public.users (
    user_id             integer generated by default as identity primary key,
    user_pseudo         varchar(50)  not null,
    user_email          varchar(100) not null,
    -- Colonne conservée ; nullable. N'y stocker qu'un HASH, jamais le mot de passe en clair.
    user_password       varchar(255),
    user_phone          varchar(255),
    user_account_status boolean      not null default true,
    user_create_at      timestamptz  not null default now(),   -- était "DataTime"
    constraint users_email_unique unique (user_email),
    constraint users_email_format check (user_email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$')
);
create unique index users_email_lower_uidx on public.users (lower(user_email));

create table public.adress (
    adress_id      integer generated by default as identity primary key,
    adress_cp      varchar(50)  not null,
    adress_name    varchar(255) not null,
    adress_type    varchar(255) not null default 'domicile',
    adress_contry  varchar(255) not null,                      -- nom conservé (typo d'origine)
    adress_user_id integer      not null                       -- était String(255)
        references public.users (user_id) on delete cascade,
    constraint adress_type_check check (adress_type in ('domicile', 'travail', 'autre'))
);
create index adress_user_idx on public.adress (adress_user_id);

-- ---------------------------------------------------------------------
-- 2. CATALOGUE : marques, catégories, produits, variantes, prix
-- ---------------------------------------------------------------------
create table public.marques (
    marque_id   integer generated by default as identity primary key,
    marque_name varchar(255) not null,
    marque_ref  varchar(255),
    constraint marques_name_unique unique (marque_name),
    constraint marques_ref_unique  unique (marque_ref)
);

create table public.categorie (
    category_id          integer generated by default as identity primary key,
    category_name        varchar(255) not null,
    category_parent_name varchar(255),                         -- conservé (dénormalisé)
    category_child_name  varchar(255),                         -- conservé (dénormalisé)
    category_created_at  timestamptz  not null default now(),
    -- [AJOUT] vraie hiérarchie (auto-référence) ; la source de vérité
    category_parent_id   integer references public.categorie (category_id) on delete set null,
    constraint categorie_no_self_parent check (category_parent_id is distinct from category_id)
);
create unique index categorie_name_parent_uidx
    on public.categorie (coalesce(category_parent_id, 0), lower(category_name));
create index categorie_parent_idx on public.categorie (category_parent_id);

create table public.product (
    product_id          integer generated by default as identity primary key,
    product_name        varchar(255) not null,
    product_ref         varchar(255) not null,
    product_desc        text,
    product_categorie   varchar(255),        -- legacy : libellé dérivé de product_category_id
    product_create_at   timestamptz not null default now(),    -- était String
    product_marque_id   integer references public.marques (marque_id) on delete set null,
    product_category_id integer references public.categorie (category_id) on delete set null,
    constraint product_name_unique unique (product_name),
    constraint product_ref_unique  unique (product_ref)
);
create index product_marque_idx   on public.product (product_marque_id);
create index product_category_idx on public.product (product_category_id);

create table public.category_pivot (
    product_id  integer not null references public.product (product_id)     on delete cascade,
    category_id integer not null references public.categorie (category_id)  on delete cascade,
    primary key (product_id, category_id)
);
create index category_pivot_category_idx on public.category_pivot (category_id);

create table public.variantes (
    variante_id         integer generated by default as identity primary key,
    variante_size       varchar(50),
    variante_color      varchar(50),
    -- Prix courant (type manquant à l'origine). Synchronisé depuis price_historique.
    variante_price      numeric(12, 2) not null check (variante_price >= 0),
    variante_create_at  timestamptz    not null default now(),
    variante_product_id integer        not null
        references public.product (product_id) on delete cascade,
    constraint variantes_unique_combo
        unique nulls not distinct (variante_product_id, variante_size, variante_color)
);
create index variantes_product_idx on public.variantes (variante_product_id);

create table public.currency (
    currency_id   integer generated by default as identity primary key,
    currency_name varchar(50) not null,
    constraint currency_name_unique unique (currency_name)
);

create table public.price_historique (
    price_id          integer generated by default as identity primary key,
    price_amount      numeric(12, 2) not null check (price_amount >= 0),  -- type manquant
    create_at         timestamptz    not null default now(),              -- était String
    currency_id       integer        not null references public.currency (currency_id),
    price_variante_id integer        not null
        references public.variantes (variante_id) on delete cascade
);
create index price_hist_variante_date_idx on public.price_historique (price_variante_id, create_at desc);
create index price_hist_currency_idx      on public.price_historique (currency_id);

-- Favoris / wishlist (« Product_Pivot » : produit <-> utilisateur, many-to-many)
create table public.product_pivot (
    product_id integer not null references public.product (product_id) on delete cascade,
    user_id    integer not null references public.users (user_id)      on delete cascade,
    pivot_created_at timestamptz not null default now(),                  -- [AJOUT]
    primary key (product_id, user_id)
);
create index product_pivot_user_idx on public.product_pivot (user_id);

-- ---------------------------------------------------------------------
-- 3. PANIER
-- ---------------------------------------------------------------------
create table public.panier (
    panier_id      integer generated by default as identity primary key,
    panier_user_id integer not null references public.users (user_id) on delete cascade
);
create index panier_user_idx on public.panier (panier_user_id);

create table public.panier_items (
    panier_items_id         integer generated by default as identity primary key,
    panier_id               integer not null references public.panier (panier_id) on delete cascade,
    panier_items_variante_id integer not null references public.variantes (variante_id) on delete cascade,
    panier_items_quantity   integer not null default 1 check (panier_items_quantity > 0),
    constraint panier_items_unique unique (panier_id, panier_items_variante_id)
);
create index panier_items_variante_idx on public.panier_items (panier_items_variante_id);

-- ---------------------------------------------------------------------
-- 4. COMMANDES (membres et invités)
-- ---------------------------------------------------------------------
create table public.commandes (
    commande_id      integer generated by default as identity primary key,
    -- NULL pour une commande invitée ; SET NULL pour conserver l'historique comptable
    commande_user_id integer references public.users (user_id) on delete set null,
    commande_ref     varchar(255) not null,
    commande_date    timestamptz  not null default now(),     -- était String
    commande_status  varchar(50)  not null default 'en_attente',
    -- Adresse figée au moment de la commande (fonctionne aussi pour les invités)
    commande_adress  text,
    -- [AJOUT] lien optionnel vers l'adresse enregistrée du membre
    commande_adress_id integer references public.adress (adress_id) on delete set null,
    constraint commandes_ref_unique unique (commande_ref),
    constraint commandes_status_check
        check (commande_status in ('en_attente', 'payee', 'expediee', 'livree', 'annulee', 'remboursee'))
);
create index commandes_user_idx   on public.commandes (commande_user_id);
create index commandes_adress_idx on public.commandes (commande_adress_id);
create index commandes_date_idx   on public.commandes (commande_date desc);

create table public.commandes_items (
    commande_items_id    integer generated by default as identity primary key,
    commande_id          integer not null references public.commandes (commande_id) on delete cascade,
    -- RESTRICT : on ne supprime pas une variante déjà vendue
    commande_variante_id integer not null references public.variantes (variante_id) on delete restrict,
    commande_unique_price numeric(12, 2) not null check (commande_unique_price >= 0),  -- prix unitaire figé
    quantity             integer not null default 1 check (quantity > 0),
    constraint commandes_items_unique unique (commande_id, commande_variante_id)
);
create index commandes_items_variante_idx on public.commandes_items (commande_variante_id);

create table public.user_guest (
    user_guest_id     integer generated by default as identity primary key,
    user_guest_number varchar(255) not null,
    -- Redondant avec commandes_userguest : conservé, nullable
    commande_id       integer references public.commandes (commande_id) on delete set null
);
create index user_guest_commande_idx on public.user_guest (commande_id);

create table public.commandes_userguest (
    id            integer generated by default as identity primary key,
    commande_id   integer not null references public.commandes (commande_id) on delete cascade,
    user_guest_id integer not null references public.user_guest (user_guest_id) on delete cascade,
    constraint commandes_userguest_unique unique (commande_id, user_guest_id)
);
create index commandes_userguest_guest_idx on public.commandes_userguest (user_guest_id);

-- ---------------------------------------------------------------------
-- 5. PROMOTIONS
-- ---------------------------------------------------------------------
create table public.promotion (
    promotion_id           integer generated by default as identity primary key,
    promotion_category_id  integer references public.categorie (category_id) on delete cascade,
    promotion_product_id   integer references public.product (product_id)    on delete cascade,
    promotion_expire_date  timestamptz not null,
    promotion_created_date timestamptz not null default now(),
    constraint promotion_target_check
        check (num_nonnulls(promotion_category_id, promotion_product_id) >= 1),
    constraint promotion_dates_check check (promotion_expire_date > promotion_created_date)
);
create index promotion_category_idx on public.promotion (promotion_category_id);
create index promotion_product_idx  on public.promotion (promotion_product_id);

create table public.reduction (
    reduction_id  integer generated by default as identity primary key,
    pourcentage   numeric(5, 2) not null check (pourcentage > 0 and pourcentage <= 100),
    promotion_id  integer not null references public.promotion (promotion_id) on delete cascade
);
create index reduction_promotion_idx on public.reduction (promotion_id);
