-- Identifiant métier de l'utilisateur connecté (public.users.user_id)
create function private.current_user_id() returns integer
language sql stable security definer set search_path = '' as $$
    select u.user_id from public.users u where u.auth_user_id = (select auth.uid())
$$;
revoke all on function private.current_user_id() from public;
grant execute on function private.current_user_id() to authenticated, service_role;

