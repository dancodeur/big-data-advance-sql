-- 6.1 product : libellé legacy + pivot alignés sur product_category_id
create function private.product_sync_label() returns trigger
language plpgsql set search_path = '' as $$
begin
    if new.product_category_id is not null then
        select c.category_name into new.product_categorie
        from public.categorie c where c.category_id = new.product_category_id;
    end if;
    return new;
end $$;

create trigger product_sync_label_trg
    before insert or update of product_category_id on public.product
    for each row execute function private.product_sync_label();

create function private.product_sync_pivot() returns trigger
language plpgsql set search_path = '' as $$
begin
    if new.product_category_id is not null then
        insert into public.category_pivot (product_id, category_id)
        values (new.product_id, new.product_category_id)
        on conflict do nothing;
    end if;
    return null;
end $$;

create trigger product_sync_pivot_trg
    after insert or update of product_category_id on public.product
    for each row execute function private.product_sync_pivot();

-- 6.2 variantes.variante_price = dernier prix de price_historique
create function private.variante_sync_price() returns trigger
language plpgsql set search_path = '' as $$
declare
    v_id integer;
begin
    foreach v_id in array array_remove(array[
        case when tg_op in ('INSERT', 'UPDATE') then new.price_variante_id end,
        case when tg_op in ('UPDATE', 'DELETE') then old.price_variante_id end
    ], null)
    loop
        update public.variantes v
           set variante_price = h.price_amount
          from (select price_amount
                  from public.price_historique
                 where price_variante_id = v_id
                 order by create_at desc, price_id desc
                 limit 1) h
         where v.variante_id = v_id
           and v.variante_price is distinct from h.price_amount;
    end loop;
    return null;
end $$;

create trigger variante_sync_price_trg
    after insert or update or delete on public.price_historique
    for each row execute function private.variante_sync_price();

